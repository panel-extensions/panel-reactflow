"""Generate Panel widget forms from JSON Schema property definitions.

The widgets come from ``panel_material_ui`` when it is installed and
from ``panel.widgets`` otherwise.
"""

from __future__ import annotations

import datetime as dt
import logging
import sys
from typing import Any

import panel as pn
import param  # type: ignore
from panel.config import config
from panel.layout.base import ListLike, Panel
from panel.pane.base import PaneBase
from panel.widgets.base import WidgetBase

_LOGGER = logging.getLogger("panel.reactflow")

_DATE_FORMATS = ("date", "date-time", "datetime")

_MISSING = object()


def _import_material_ui():
    """Import ``panel_material_ui`` without changing the global design.

    Importing ``panel_material_ui`` sets ``pn.config.design`` to
    ``MaterialDesign`` for the whole process, which restyles every Panel
    component in the application. Its own components apply
    ``MaterialDesign`` regardless, so when this import is the one that
    loads the package the previous global design is restored. An
    application that imports ``panel_material_ui`` itself keeps its
    behavior, as long as it imports it first or sets
    ``pn.config.design`` explicitly.
    """
    if "panel_material_ui" in sys.modules:
        return sys.modules["panel_material_ui"]
    design = object.__getattribute__(config, "design")
    try:
        import panel_material_ui
    except ImportError:
        return None
    finally:
        if object.__getattribute__(config, "design") is not design:
            param.Parameterized.__setattr__(config, "design", design)
    return panel_material_ui


_pmui = _import_material_ui()
_widgets = _pmui if _pmui is not None else pn.widgets
_layout = _pmui.Paper if _pmui is not None else pn.Column


def _parse_datetime(value: Any) -> dt.datetime:
    """Parse an ISO 8601 string, date or datetime into a naive UTC datetime."""
    if isinstance(value, dt.datetime):
        parsed = value
    elif isinstance(value, dt.date):
        return dt.datetime.combine(value, dt.time())
    elif isinstance(value, str):
        text = value.strip()
        if text[-1:] in ("Z", "z"):
            text = text[:-1] + "+00:00"
        parsed = dt.datetime.fromisoformat(text)
    else:
        raise TypeError(f"Cannot interpret {value!r} as a date")
    if parsed.tzinfo is not None:
        parsed = parsed.astimezone(dt.timezone.utc).replace(tzinfo=None)
    return parsed


def to_json_value(value: Any) -> Any:
    """Convert widget values that JSON cannot represent (dates) to ISO strings."""
    if isinstance(value, (dt.date, dt.datetime)):
        return value.isoformat()
    if isinstance(value, (list, tuple)) and any(isinstance(v, (dt.date, dt.datetime)) for v in value):
        return [to_json_value(v) for v in value]
    return value


def _title_kwargs(wtype: Any, title: str) -> dict[str, str]:
    """Pass the title as ``label`` where supported, since newer Panel deprecates ``name``."""
    params = getattr(wtype, "param", None)
    return {"label": title} if params is not None and "label" in params else {"name": title}


def _json_pointer(root: Any, pointer: str) -> Any:
    target = root
    for part in pointer.split("/"):
        if not part:
            continue
        part = part.replace("~1", "/").replace("~0", "~")
        target = target[int(part)] if isinstance(target, list) else target[part]
    return target


class JSONSchema(PaneBase):
    """Render a form of widgets for the properties of a JSON Schema.

    Each property is mapped to a widget based on its ``enum``, ``type``,
    ``format`` and bounds. ``$ref`` pointers into ``definitions``,
    nullable ``anyOf``/``oneOf`` unions, type lists and ``const`` are
    resolved first, so the schemas generated by ``param`` and ``pydantic``
    produce proper widgets. A property no widget can represent is shown
    as a ``LiteralInput`` instead of failing the whole form.
    """

    default_layout = param.ClassSelector(
        default=_layout,
        class_=(
            Panel,
            ListLike,
        ),
        is_instance=False,
        doc="""
        Defines the layout the model(s) returned by the pane will
        be placed in.""",
    )

    definitions = param.Dict(
        default={},
        doc="""
        Schema definitions (the ``$defs`` or ``definitions`` of the root
        schema) that ``$ref`` pointers in the properties resolve against.""",
    )

    multi = param.Boolean(
        default=True,
        doc="""
        Whether to pick multi-select and range widgets by default.""",
    )

    properties = param.List(
        default=[],
        doc="""
        If set this serves as a whitelist of properties to display on
        the supplied schema object.""",
    )

    schema = param.Dict(
        doc="""
        Mapping from property name to the JSON Schema of that property,
        i.e. the ``properties`` of an object schema.""",
    )

    widgets = param.Dict(
        doc="""
        Dictionary of widget overrides, mapping from parameter name to a
        widget class, a widget instance, or a dict of widget keyword
        arguments with an optional ``type`` key holding the widget class.""",
    )

    _precedence = ["enum", "type"]

    _unpack = True

    _select_widget = _widgets.Select
    _multi_select_widget = _widgets.MultiChoice
    _bounded_number_widget = _widgets.FloatSlider
    _bounded_number_range_widget = _widgets.RangeSlider
    _unbounded_number_widget = _widgets.FloatInput
    _list_select_widget = _widgets.MultiChoice
    _bounded_int_widget = _widgets.IntSlider
    _bounded_int_range_widget = _widgets.IntRangeSlider
    _unbounded_int_widget = _widgets.IntInput
    _string_widget = _widgets.TextInput
    _boolean_widget = _widgets.Checkbox
    _literal_widget = _widgets.LiteralInput
    _unbounded_date_widget = _widgets.DatePicker
    _date_range_widget = _widgets.DateRangeSlider
    _unbounded_datetime_widget = _widgets.DatetimePicker
    _datetime_range_widget = _widgets.DatetimeRangePicker

    def __init__(self, object=None, schema=None, **params):
        if schema is not None:
            params["schema"] = schema
        super().__init__(object, **params)
        self._widgets = {}
        self._resolved = {}
        self._nullable = set()
        self._update_widgets_from_schema()

    # Schema resolution

    def _lookup_ref(self, ref: str) -> dict[str, Any]:
        if not ref.startswith("#/"):
            raise ValueError(f"Only local $ref pointers are supported, got {ref!r}")
        root = {"$defs": self.definitions, "definitions": self.definitions}
        return _json_pointer(root, ref[2:])

    def _resolve(self, schema: dict[str, Any], _seen: tuple[str, ...] = ()) -> tuple[dict[str, Any], bool]:
        """Reduce *schema* to a single property schema.

        Returns the resolved schema and whether ``null`` is an allowed
        value. Keys on the outer schema (``title``, ``default``, ...)
        take precedence over those of the schema they refer to.
        """
        schema = dict(schema)
        nullable = False
        ref = schema.pop("$ref", None)
        if ref is not None:
            if ref in _seen:
                raise ValueError(f"Recursive $ref {ref!r}")
            target, nullable = self._resolve(self._lookup_ref(ref), (*_seen, ref))
            schema = {**target, **schema}
        for sub in schema.pop("allOf", None) or []:
            sub, sub_nullable = self._resolve(sub, _seen)
            schema = {**sub, **schema}
            nullable = nullable or sub_nullable
        for key in ("anyOf", "oneOf"):
            options = schema.pop(key, None)
            if not options:
                continue
            resolved = []
            for sub in options:
                sub, sub_nullable = self._resolve(sub, _seen)
                nullable = nullable or sub_nullable
                if sub.get("type") == "null":
                    nullable = True
                else:
                    resolved.append(sub)
            if len(resolved) == 1:
                schema = {**resolved[0], **schema}
                continue
            if "enum" not in schema and resolved and all("enum" in sub for sub in resolved):
                schema["enum"] = [value for sub in resolved for value in sub["enum"]]
            types = {sub.get("type") for sub in resolved}
            if len(types) == 1 and None not in types and "type" not in schema:
                schema["type"] = types.pop()
        if "const" in schema and "enum" not in schema:
            schema["enum"] = [schema["const"]]
        if isinstance(schema.get("type"), list):
            types = [t for t in schema["type"] if t != "null"]
            nullable = nullable or len(types) < len(schema["type"])
            if len(types) == 1:
                schema["type"] = types[0]
            elif types:
                del schema["type"]
            else:
                schema["type"] = "null"
        if "enum" in schema and None in schema["enum"]:
            nullable = True
            schema["enum"] = [value for value in schema["enum"] if value is not None]
        return schema, nullable

    # Widget selection

    @staticmethod
    def _bounds(schema: dict[str, Any]) -> tuple[Any, Any]:
        lower = upper = None
        for key in ("minimum", "inclusiveMinimum", "exclusiveMinimum"):
            if isinstance(schema.get(key), (int, float)) and not isinstance(schema.get(key), bool):
                lower = schema[key]
                break
        for key in ("maximum", "inclusiveMaximum", "exclusiveMaximum"):
            if isinstance(schema.get(key), (int, float)) and not isinstance(schema.get(key), bool):
                upper = schema[key]
                break
        return lower, upper

    def _array_type(self, schema):
        items = schema.get("prefixItems", schema.get("items"))
        additional = schema.get("additionalItems")
        if items is None and isinstance(additional, dict) and schema.get("minItems") == schema.get("maxItems") == 2:
            items = [additional, additional]
        if isinstance(items, list):
            resolved = [self._resolve(item)[0] for item in items]
            types = {item.get("type") for item in resolved}
            bounds = {self._bounds(item) for item in resolved}
            if len(resolved) == 2 and types <= {"number", "integer"} and len(bounds) == 1:
                lower, upper = bounds.pop()
                if lower is not None and upper is not None:
                    if types == {"integer"}:
                        return self._bounded_int_range_widget, {"start": int(lower), "end": int(upper)}
                    return self._bounded_number_range_widget, {"start": float(lower), "end": float(upper)}
        elif isinstance(items, dict):
            item = self._resolve(items)[0]
            if "enum" in item:
                return self._list_select_widget, {"options": list(item["enum"])}
        return self._literal_widget, {"type": (list, tuple)}

    def _number_type(self, schema):
        lower, upper = self._bounds(schema)
        if lower is not None and upper is not None:
            wtype = self._bounded_number_range_widget if self.multi else self._bounded_number_widget
            return wtype, {"start": float(lower), "end": float(upper)}
        kwargs = {}
        if lower is not None:
            kwargs["start"] = float(lower)
        if upper is not None:
            kwargs["end"] = float(upper)
        return self._unbounded_number_widget, kwargs

    def _integer_type(self, schema):
        lower, upper = self._bounds(schema)
        if lower is not None and upper is not None:
            wtype = self._bounded_int_range_widget if self.multi else self._bounded_int_widget
            return wtype, {"start": int(lower), "end": int(upper)}
        kwargs = {"step": 1}
        if lower is not None:
            kwargs["start"] = int(lower)
        if upper is not None:
            kwargs["end"] = int(upper)
        return self._unbounded_int_widget, kwargs

    def _boolean_type(self, schema):
        return self._boolean_widget, {}

    def _object_type(self, schema):
        return self._literal_widget, {"type": dict}

    def _null_type(self, schema):
        return None, {}

    def _date_bounds(self, schema: dict[str, Any]) -> tuple[Any, Any]:
        for lower_key, upper_key in (("formatMinimum", "formatMaximum"), ("inclusiveMinimum", "inclusiveMaximum")):
            if lower_key in schema and upper_key in schema:
                return _parse_datetime(schema[lower_key]), _parse_datetime(schema[upper_key])
        return None, None

    def _string_type(self, schema):
        fmt = schema.get("format")
        if fmt not in _DATE_FORMATS:
            return self._string_widget, {}
        is_date = fmt == "date"
        lower, upper = self._date_bounds(schema)
        if lower is None:
            return (self._unbounded_date_widget if is_date else self._unbounded_datetime_widget), {}
        if is_date:
            lower, upper = lower.date(), upper.date()
        if self.multi:
            return (self._date_range_widget if is_date else self._datetime_range_widget), {"start": lower, "end": upper}
        return (self._unbounded_date_widget if is_date else self._unbounded_datetime_widget), {"start": lower, "end": upper}

    def _enum(self, schema):
        wtype = self._multi_select_widget if self.multi else self._select_widget
        try:
            options = sorted(schema["enum"])
        except TypeError:
            options = list(schema["enum"])
        return wtype, {"options": options}

    def _widget_type(self, prop, schema):
        if prop == "enum":
            return self._enum(schema)
        method = getattr(self, f"_{schema[prop]}_{prop}", None) if prop is not None else None
        if method is None:
            return self._literal_widget, {}
        return method(schema)

    # Values

    def _coerce_value(self, value: Any, schema: dict[str, Any], wtype: Any, nullable: bool = False) -> Any:
        """Convert a data value into one the widget accepts, or ``_MISSING``."""
        if value is None:
            value_param = getattr(wtype, "param", None)
            if nullable and value_param is not None and "value" in value_param and value_param["value"].allow_None:
                return None
            return _MISSING
        if schema.get("type") == "string" and schema.get("format") in _DATE_FORMATS:
            convert = (lambda v: _parse_datetime(v).date()) if schema["format"] == "date" else _parse_datetime
            try:
                if isinstance(value, (list, tuple)):
                    return tuple(convert(v) for v in value)
                return convert(value)
            except (TypeError, ValueError):
                return value
        if schema.get("type") == "integer" and isinstance(value, float) and value.is_integer():
            return int(value)
        value_param = wtype.param["value"] if isinstance(wtype, type) and issubclass(wtype, param.Parameterized) and "value" in wtype.param else None
        if isinstance(value, list) and isinstance(value_param, param.Tuple):
            return tuple(value)
        return value

    def _build_widget(self, name: str, schema: dict[str, Any], value: Any) -> WidgetBase | None:
        resolved, nullable = self._resolve(schema)
        self._resolved[name] = resolved
        if nullable:
            self._nullable.add(name)
        override = (self.widgets or {}).get(name)
        if isinstance(override, WidgetBase):
            return override
        prop = next((prop for prop in self._precedence if prop in resolved), None)
        wtype, kwargs = self._widget_type(prop, resolved)
        if isinstance(override, dict):
            override = dict(override)
            wtype = override.pop("type", wtype)
            kwargs = {**kwargs, **override}
        elif override is not None:
            wtype = override
        if wtype is None:
            return None
        if isinstance(wtype, WidgetBase):
            return wtype
        title = schema.get("title") or resolved.get("title") or name
        coerced = self._coerce_value(value, resolved, wtype, nullable)
        if coerced is not _MISSING:
            kwargs["value"] = coerced
        elif isinstance(wtype, type) and issubclass(wtype, self._literal_widget):
            kwargs["value"] = None
        try:
            return wtype(**_title_kwargs(wtype, title), **kwargs)
        except Exception:
            if "value" not in kwargs:
                raise
            _LOGGER.warning("Value %r of property %r does not fit its schema, showing it as a literal.", value, name)
            return self._literal_widget(**_title_kwargs(self._literal_widget, title), value=value)

    @param.depends("schema", "definitions", "multi", "properties", "widgets", watch=True)
    def _update_widgets_from_schema(self):
        self._widgets = {}
        self._resolved = {}
        self._nullable = set()
        if not self.schema:
            self.layout[:] = []
            return

        values = self.object or {}
        widgets = []
        for name, schema in self.schema.items():
            if name == "__len__" or self.properties and name not in self.properties:
                continue
            value = values.get(name)
            try:
                widget = self._build_widget(name, schema, value)
            except Exception:
                _LOGGER.warning("Could not build a widget for property %r from schema %r, showing it as a literal.", name, schema, exc_info=True)
                self._resolved[name] = {}
                try:
                    title = schema.get("title", name) if isinstance(schema, dict) else name
                    widget = self._literal_widget(**_title_kwargs(self._literal_widget, title), value=value)
                except Exception:
                    continue
            if widget is None:
                continue
            self._widgets[name] = widget
            widgets.append(widget)
        self.layout[:] = widgets

    @param.depends("object", watch=True)
    def _update_widget_values(self):
        self._set_widget_values(self.object or {})

    def _set_widget_values(self, values: dict[str, Any]) -> None:
        """Update the widgets of the properties in *values*, ignoring other keys."""
        for name, value in values.items():
            widget = self._widgets.get(name)
            if widget is None:
                continue
            coerced = self._coerce_value(value, self._resolved.get(name, {}), type(widget), name in self._nullable)
            if coerced is _MISSING:
                continue
            try:
                widget.value = coerced
            except Exception:
                _LOGGER.warning("Could not set property %r to %r.", name, value, exc_info=True)

    def _get_model(self, doc, root=None, parent=None, comm=None):
        model = self.layout._get_model(doc, root, parent, comm)
        self._models[root.ref["id"]] = (model, parent)
        return model

    def _cleanup(self, root):
        self.layout._cleanup(root)
        super()._cleanup(root)
